"""Адрес доставки и идентичность пользователя — разные вещи (ADR-0017, BR-010).

Адресат из реестра ролей записывается в одной из двух форм:

* ``user:<id>`` — глобальный id пользователя платформы. Единственная форма,
  которой можно написать ПЕРВЫМ: ``chat_id`` личного диалога уникален для пары
  «пользователь ↔ бот» и снаружи неизвестен (живой прогон 2026-07-26 — 404).
* ``<chat_id>`` — обычный адрес, пришедший из входящего update.

Транспорт (кому слать) и идентичность (чья это сессия) совпадают по значению
в личном чате, но НЕ совпадают по написанию: вебхук отдаёт id всегда без
префикса. Смешать их — значит завести push-сессию под ключом ``user:<id>``,
тогда как нажатие кнопки на этой же карточке придёт под ``<id>``: разные
сессии, цепочка не продолжается и молча обрывается.

Конвенция платформонезависима (BR-005): её раскрывают адаптеры — MAX в
параметр ``user_id``, Telegram простым снятием префикса (в личке ``chat_id``
равен ``user_id``).
"""

from __future__ import annotations

USER_ADDRESS_PREFIX = "user:"


def is_user_address(address: str) -> bool:
    """True — адрес записан глобальным id пользователя, а не chat_id диалога."""
    return address.startswith(USER_ADDRESS_PREFIX)


def address_identity(address: str) -> str:
    """Адрес доставки → идентичность пользователя (ключ сессии).

    Обычный адрес возвращается как есть: снимается только префикс конвенции.
    """
    return address.removeprefix(USER_ADDRESS_PREFIX)

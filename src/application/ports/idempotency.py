"""IdempotencyPort — защита приёма от повторной доставки (ADR-0004, ADR-0019).

Две модели использования:

* вебхук — ``first_time``: один ключ с единым TTL, платформа ретраит сама и
  повторную доставку достаточно отбросить;
* внешнее событие — ``reserve``/``confirm``: ключ сначала берётся коротким
  «в работе», и только фактическое исполнение продлевает его до полного TTL.
  Без этого падение процесса между ``first_time`` и отправкой сжигает
  ``event_id`` на сутки, и ретрай вызывающего получает ложный «дубль».
"""

from __future__ import annotations

import enum
from typing import Protocol


class Reservation(enum.StrEnum):
    """Исход попытки занять ключ."""

    ACQUIRED = "acquired"  # ключ наш — выполняем работу
    IN_FLIGHT = "in_flight"  # занят незавершённой попыткой — повторить позже
    DONE = "done"  # работа по ключу уже выполнена — настоящий дубль


class IdempotencyPort(Protocol):
    """Отвечает на вопрос «этот ключ виден впервые?» атомарно."""

    async def first_time(self, key: str) -> bool: ...

    async def reserve(self, key: str) -> Reservation:
        """Атомарно занимает ключ на короткий срок «в работе» (ADR-0019)."""
        ...

    async def touch(self, key: str) -> None:
        """Продлевает аренду «в работе», пока работа идёт (ADR-0019).

        Без продления короткий TTL истекает под живым исполнением, и ретрай
        вызывающего исполняет то же событие второй раз.
        """
        ...

    async def confirm(self, key: str) -> None:
        """Работа выполнена — продлевает ключ до полного TTL дедупа."""
        ...

    async def forget(self, key: str) -> None:
        """Компенсация: освобождает ключ, когда обработка после ``reserve``
        не состоялась — ретрай вызывающего с тем же ключом должен пройти.
        """
        ...
